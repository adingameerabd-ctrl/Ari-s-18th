// ========================================
// WEBSITE ELEMENTS
// ========================================

const giftGrid =
    document.getElementById("giftGrid");

const modal =
    document.getElementById("giftModal");

const closeModalButton =
    document.getElementById("closeModal");

const selectButton =
    document.getElementById("selectButton");

const categoryButtons =
    document.querySelectorAll(".category");


// ========================================
// CATEGORY NAME
// ========================================

function getCategoryName(category) {

    if (category === "electronics") {

        return "Electronics";

    }

    if (category === "miscellaneous") {

        return "Miscellaneous";

    }

    if (category === "books") {

        return "Book Collections";

    }

    return category;
}


// ========================================
// PLACEHOLDER IMAGE
// ========================================

function createPlaceholder(emoji) {

    const placeholder =
        document.createElement("div");

    placeholder.className =
        "image-placeholder";

    placeholder.textContent =
        emoji;

    return placeholder;
}


// ========================================
// DISPLAY GIFTS
// ========================================

function displayGifts(category = "all") {

    giftGrid.innerHTML = "";

    let giftsToShow;


    if (category === "all") {

        giftsToShow = gifts;

    } else {

        giftsToShow =
            gifts.filter(
                function (gift) {

                    return gift.category === category;

                }
            );

    }


    giftsToShow.forEach(
        function (gift) {

            const card =
                document.createElement("div");

            card.className =
                "gift-card";


            // -----------------------------
            // IMAGE
            // -----------------------------

            const imageWrapper =
                document.createElement("div");

            imageWrapper.className =
                "gift-image-wrapper";


            if (gift.image) {

                const image =
                    document.createElement("img");

                image.className =
                    "gift-image";

                image.src =
                    gift.image;

                image.alt =
                    gift.name;


                image.onerror =
                    function () {

                        image.remove();

                        imageWrapper.appendChild(
                            createPlaceholder(
                                gift.emoji
                            )
                        );

                    };


                imageWrapper.appendChild(
                    image
                );

            } else {

                imageWrapper.appendChild(
                    createPlaceholder(
                        gift.emoji
                    )
                );

            }


            // -----------------------------
            // INFORMATION
            // -----------------------------

            const info =
                document.createElement("div");

            info.className =
                "gift-info";


            const categoryLabel =
                document.createElement("div");

            categoryLabel.className =
                "gift-category";

            categoryLabel.textContent =
                gift.section;


            const name =
                document.createElement("div");

            name.className =
                "gift-name";

            name.textContent =
                gift.name;


            const description =
                document.createElement("div");

            description.className =
                "gift-description";

            description.textContent =
                gift.description;


            const price =
                document.createElement("div");

            price.className =
                "gift-price";

            price.textContent =
                gift.price;


            const status =
                document.createElement("div");

            status.className =
                "gift-status";


            if (gift.jointGift) {

                status.textContent =
                    "♡ Available for joint gift";

            } else {

                status.textContent =
                    "♡ Available";

            }


            // -----------------------------
            // PUT INFORMATION TOGETHER
            // -----------------------------

            info.appendChild(
                categoryLabel
            );

            info.appendChild(
                name
            );

            info.appendChild(
                description
            );

            info.appendChild(
                price
            );

            info.appendChild(
                status
            );


            card.appendChild(
                imageWrapper
            );

            card.appendChild(
                info
            );


            // -----------------------------
            // OPEN MODAL
            // -----------------------------

            card.addEventListener(
                "click",
                function () {

                    openGift(gift);

                }
            );


            giftGrid.appendChild(
                card
            );

        }
    );

}


// ========================================
// CATEGORY BUTTONS
// ========================================

categoryButtons.forEach(
    function (button) {

        button.addEventListener(
            "click",
            function () {

                categoryButtons.forEach(
                    function (otherButton) {

                        otherButton.classList.remove(
                            "active"
                        );

                    }
                );


                button.classList.add(
                    "active"
                );


                displayGifts(
                    button.dataset.category
                );

            }
        );

    }
);


// ========================================
// OPEN GIFT MODAL
// ========================================

function openGift(gift) {

    const modalImageWrapper =
        document.getElementById(
            "modalImageWrapper"
        );

    const modalCategory =
        document.getElementById(
            "modalCategory"
        );

    const modalName =
        document.getElementById(
            "modalName"
        );

    const modalDescription =
        document.getElementById(
            "modalDescription"
        );

    const modalPrice =
        document.getElementById(
            "modalPrice"
        );

    const modalStatus =
        document.getElementById(
            "modalStatus"
        );


    modalCategory.textContent =
        gift.section;


    modalName.textContent =
        gift.name;


    modalDescription.textContent =
        gift.description;


    modalPrice.textContent =
        gift.price;


    modalStatus.textContent =
        gift.jointGift
            ? "♡ Available for a joint gift"
            : "♡ Available";


    // -----------------------------
    // IMAGE
    // -----------------------------

    modalImageWrapper.innerHTML = "";


    if (gift.image) {

        const image =
            document.createElement("img");

        image.src =
            gift.image;

        image.alt =
            gift.name;


        image.onerror =
            function () {

                modalImageWrapper.innerHTML = "";

                modalImageWrapper.appendChild(
                    createPlaceholder(
                        gift.emoji
                    )
                );

            };


        modalImageWrapper.appendChild(
            image
        );

    } else {

        modalImageWrapper.appendChild(
            createPlaceholder(
                gift.emoji
            )
        );

    }


    modal.classList.remove(
        "hidden"
    );

}


// ========================================
// CLOSE MODAL
// ========================================

function closeModal() {

    modal.classList.add(
        "hidden"
    );

}


closeModalButton.addEventListener(
    "click",
    closeModal
);


modal.addEventListener(
    "click",
    function (event) {

        if (
            event.target === modal
        ) {

            closeModal();

        }

    }
);


// ========================================
// SELECT GIFT
// ========================================

selectButton.addEventListener(
    "click",
    function () {

        alert(
            "The anonymous gift selection system will be connected next! ♡"
        );

    }
);


// ========================================
// START WEBSITE
// ========================================

displayGifts("all");
